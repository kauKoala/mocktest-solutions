#include <iostream>

using namespace std;

int main() {
    // 이웃한 두 수의 최대공약수(gcd)가 모두 다른 수열을 만드는 문제

    // 연속된 홀수 두 개를 곱한 수를 차례로 놓는다.
    // 1*3, 3*5, 5*7, 7*9, ... = 3, 15, 35, 63, ...

    // 이웃한 두 수 (2i-1)*(2i+1) 과 (2i+1)*(2i+3) 은 (2i+1)을 공통으로 가진다.
    // 남은 (2i-1)과 (2i+3)의 공약수는 두 수의 차이인 4의 약수여야 하는데, 둘 다 홀수이므로 1뿐이다.
    // 따라서 이웃한 두 수의 gcd는 2i+1이 되고, gcd가 3, 5, 7, ... 로 모두 다르다.
    // (n이 최대 10000이어도 가장 큰 수는 19999*20001 = 약 4억이므로 10^18을 넘지 않는다)

    // 입력 처리
    int t;
    cin >> t;

    for (int tc = 0; tc < t; tc++) {
        int n;
        cin >> n;

        // 연속된 홀수 두 개를 곱한 수를 차례로 출력
        for (int i = 1; i <= n; i++) {
            int num = (2 * i - 1) * (2 * i + 1);   // 최대 약 4억이므로 int 범위 안에 들어온다
            cout << num << " ";
        }
        cout << "\n";
    }

    return 0;
}
