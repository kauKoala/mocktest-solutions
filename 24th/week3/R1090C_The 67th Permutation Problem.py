import sys
input = sys.stdin.readline

# 순열을 3개씩 나눈 블록들의 중앙값 합이 최대가 되도록 순열을 만드는 문제

# 중앙값은 블록에서 두 번째로 큰 수이므로, 같은 블록 안에 자기보다 큰 수가 하나는 있어야 한다.
# 따라서 남은 수 중 가장 큰 수 2개와 가장 작은 수 1개를 한 블록으로 묶으면
# 큰 수 2개 중 작은 쪽이 중앙값이 되고, 이렇게 묶을 때 중앙값의 합이 가장 크다.
# 예를 들어 n = 2 이면 (1, 5, 6), (2, 3, 4) 로 묶고, 중앙값의 합은 5 + 3 = 8이 된다.

# 입력 처리
t = int(input())

for _ in range(t):
    n = int(input())

    # 정답 순열을 저장할 리스트
    p = []

    small = 1       # 아직 사용하지 않은 수 중 가장 작은 수
    big = 3 * n     # 아직 사용하지 않은 수 중 가장 큰 수

    # n개의 블록을 차례로 만든다
    for _ in range(n):
        p.append(small)     # 가장 작은 수 1개
        p.append(big - 1)   # 가장 큰 수 2개
        p.append(big)

        small += 1
        big -= 2

    # 출력 처리
    print(*p)
