import sys
input = sys.stdin.readline

# l부터 r까지 적힌 수를 모두 0으로 만드는 최소 연산 횟수를 구하는 문제이
# 한 연산마다 두 수를 골라 하나는 3배, 다른 하나는 3으로 나눈 몫으로 바꾼다.

# 어떤 수를 0으로 만들려면, y 자리에 두고 floor(y/3) 연산을 반복해야 한다.
# 즉 그 수를 3으로 계속 나누는 횟수만큼 연산이 든다.
# 이 횟수는 작은 수의 값에서 재귀적으로 구할 수 있다. (-> 3으로 나눈 몫에 대한 횟수 + 1)

# 칠판에 0이 하나도 없을 때는, 가장 작은 수 l을 먼저 0으로 만들어야 한다.
# 이때 l을 없애기 전에 다른 수들이 3배씩 커지므로, l을 0으로 만드는 데 드는 연산이 한 번 더 필요하다.
# 첫 0이 생긴 뒤에는 x=0을 두고 나머지 수들만 y 쪽으로 나누면 되므로, 각 수마다 위에서 구한 횟수만큼 더하면 된다.


# 최대 N 선언
MAX_N = 200000

# 각 정수마다 0이 될 때까지 3으로 나누는 횟수를 미리 계산
cost = [0] * (MAX_N + 1)
for i in range(1, MAX_N + 1):
    cost[i] = cost[i // 3] + 1

# 횟수들의 누적합 계산
dp = [0] * (MAX_N + 1)
for i in range(1, MAX_N + 1):
    dp[i] = dp[i - 1] + cost[i] # 1부터 i까지 더한 값

# 테스트 케이스 입력 처리
t = int(input().strip())
for _ in range(t):
    l, r = map(int, input().split())

    # l부터 r까지 횟수 합 + 최솟값 l에 대한 추가 연산
    answer = cost[l] + dp[r] - dp[l - 1]

    # 출력 처리
    print(answer)
