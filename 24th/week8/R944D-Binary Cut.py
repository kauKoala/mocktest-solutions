import sys
input = sys.stdin.readline

# 이진 문자열을 최소 몇 조각으로 잘라야, 조각들을 재배치해서 0...01...1 (정렬된 문자열)을 만들 수 있는지 구하는 문제

# 1. 같은 문자가 연속된 덩어리(예: 000, 11)는 자를 필요가 없다. 덩어리째로 옮기면 되기 때문이다.
# 2. 반대로 0과 1이 바뀌는 경계는 기본적으로 모두 잘라야 한다.
#    자르지 않으면 "10"이나 "01" 같은 조각이 생기는데, 정렬된 문자열 안에 "10"은 들어갈 수 없기 때문이다.
#    따라서 기본 조각 수 = (문자가 바뀌는 경계의 수) + 1
# 3. 단, "01" 모양의 경계 하나는 자르지 않아도 된다.
#    정렬된 문자열 0...01...1 에는 0에서 1로 바뀌는 지점이 정확히 한 곳 있으므로,
#    "0...01...1" 모양의 조각 하나는 그 자리에 그대로 놓을 수 있다.
#    그러므로 "01" 경계가 하나라도 있으면 조각 수에서 1을 뺀다.

# 테스트 케이스 입력 처리
t = int(input())

for _ in range(t):
    # 이진 문자열 입력 처리
    s = input().strip()

    # 변수 선언
    answer = 1        # 조각 수 (자르지 않으면 1조각)
    has_01 = False    # "01" 경계가 있는지 여부를 저장할 변수

    # 이웃한 두 문자를 비교하며 경계 탐색
    for i in range(len(s) - 1):

        # 문자가 바뀌는 경계라면 조각 수 1 증가
        if s[i] != s[i + 1]:
            answer += 1

        # 그 경계가 "01" 모양이라면 표시
        if s[i] == '0' and s[i + 1] == '1':
            has_01 = True

    # "01" 경계가 하나라도 있으면 그 경계는 자르지 않아도 되므로 1 감소
    if has_01:
        answer -= 1

    # 출력 처리
    print(answer)
